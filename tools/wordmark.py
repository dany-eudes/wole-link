#!/usr/bin/env python3
"""Turns the WOL•E app's wordmark (res/drawable/logo_wordmark.xml, the dark variant for light
backgrounds) into src/wordmark.rs: each path flattened into polygons, with its color untouched.

    python3 tools/wordmark.py path/to/logo_wordmark.xml

Standard library only. The colors are the app's and are never changed here.
"""

import math
import re
import sys
import xml.etree.ElementTree as ET

ANDROID = "{http://schemas.android.com/apk/res/android}"
CURVE_STEPS = 12


def tokens(d):
    for match in re.finditer(r"[A-Za-z]|-?\d*\.?\d+(?:[eE][-+]?\d+)?", d):
        yield match.group()


def arc(p0, rx, ry, phi, large, sweep, p1):
    """SVG endpoint arc to points (SVG 1.1, appendix F.6)."""
    (x1, y1), (x2, y2) = p0, p1
    if rx == 0 or ry == 0:
        return [p1]
    cos, sin = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    xp, yp = cos * dx + sin * dy, -sin * dx + cos * dy
    rx, ry = abs(rx), abs(ry)
    lam = xp**2 / rx**2 + yp**2 / ry**2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx**2 * ry**2 - rx**2 * yp**2 - ry**2 * xp**2
    den = rx**2 * yp**2 + ry**2 * xp**2
    coef = math.sqrt(max(0, num / den)) * (-1 if large == sweep else 1)
    cxp, cyp = coef * rx * yp / ry, -coef * ry * xp / rx
    cx = cos * cxp - sin * cyp + (x1 + x2) / 2
    cy = sin * cxp + cos * cyp + (y1 + y2) / 2

    def angle(ux, uy, vx, vy):
        a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
        return a

    t1 = angle(1, 0, (xp - cxp) / rx, (yp - cyp) / ry)
    dt = angle((xp - cxp) / rx, (yp - cyp) / ry, (-xp - cxp) / rx, (-yp - cyp) / ry)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    steps = max(4, int(abs(dt) / (math.pi / 16)))
    points = []
    for i in range(1, steps + 1):
        t = t1 + dt * i / steps
        x, y = rx * math.cos(t), ry * math.sin(t)
        points.append((cos * x - sin * y + cx, sin * x + cos * y + cy))
    return points


def flatten(d):
    """Absolute M, L, C, A, Z (what the wordmark uses) into closed polygons."""
    polygons, current = [], []
    it = tokens(d)
    command = None
    pending = None
    def num():
        return float(next(it))
    while True:
        tok = pending if pending is not None else next(it, None)
        pending = None
        if tok is None:
            break
        if tok.isalpha():
            command = tok
            if command in "Zz":
                if current:
                    polygons.append(current)
                current = []
                continue
            tok = next(it)
        # tok holds the first number of the command's arguments
        first = float(tok)
        if command == "M":
            if current:
                polygons.append(current)
            current = [(first, num())]
            command = "L"  # further pairs are lines
        elif command == "L":
            current.append((first, num()))
        elif command == "C":
            p0 = current[-1]
            p1 = (first, num())
            p2 = (num(), num())
            p3 = (num(), num())
            for i in range(1, CURVE_STEPS + 1):
                t = i / CURVE_STEPS
                u = 1 - t
                current.append(tuple(u**3 * a + 3 * u * u * t * b + 3 * u * t * t * c + t**3 * e
                                     for a, b, c, e in zip(p0, p1, p2, p3)))
        elif command == "A":
            rx, ry, phi = first, num(), num()
            large, sweep = int(num()), int(num())
            p1 = (num(), num())
            current += arc(current[-1], rx, ry, phi, large, sweep, p1)
        else:
            raise ValueError(f"path command {command} not handled")
    if current:
        polygons.append(current)
    # Drop repeated points (the drawable has many zero-length lines).
    clean = []
    for poly in polygons:
        out = [poly[0]]
        for p in poly[1:]:
            if abs(p[0] - out[-1][0]) > 1e-3 or abs(p[1] - out[-1][1]) > 1e-3:
                out.append(p)
        clean.append(out)
    return clean


def main(source):
    root = ET.parse(source).getroot()
    width = float(root.get(ANDROID + "viewportWidth"))
    height = float(root.get(ANDROID + "viewportHeight"))
    shapes = []
    for path in root.iter("path"):
        color = path.get(ANDROID + "fillColor").lstrip("#")
        shapes.append((int(color[-6:], 16), flatten(path.get(ANDROID + "pathData"))))

    out = ["//! The WOL•E wordmark, from the app's res/drawable/logo_wordmark.xml (the dark variant,",
           "//! for light backgrounds). Generated by tools/wordmark.py: don't edit; the colors are the",
           "//! app's and never change.", "",
           f"pub const WIDTH: f32 = {width};", f"pub const HEIGHT: f32 = {height};", "",
           "/// Fill color (0xRRGGBB) and polygons, painted in order with the nonzero rule.",
           "pub const SHAPES: &[(u32, &[&[(f32, f32)]])] = &["]
    for color, polygons in shapes:
        out.append(f"    (0x{color:06X}, &[")
        for poly in polygons:
            pts = ", ".join(f"({x:.2f}, {y:.2f})" for x, y in poly)
            out.append(f"        &[{pts}],")
        out.append("    ]),")
    out.append("];")
    open("src/wordmark.rs", "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
